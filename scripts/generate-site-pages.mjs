import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const appDir = join(root, 'apps/web/src/app');
const outFile = join(root, 'packages/validation/src/site-pages.catalog.ts');

function sitePageSlugFromPath(path) {
  const body = path === '/' ? 'home' : path.replace(/^\//, '').replaceAll('/', '-');
  return `site-${body}`;
}

const TITLE_WORDS = {
  ai: 'AI',
  api: 'API',
  ev: 'EV',
  faq: 'FAQ',
  faqs: 'FAQs',
  rto: 'RTO',
  sdk: 'SDK',
  seo: 'SEO',
  tco: 'TCO',
};

function titleFromPath(path) {
  if (path === '/') return 'Home';
  return path
    .split('/')
    .filter(Boolean)
    .map((segment) =>
      segment
        .split('-')
        .filter(Boolean)
        .map((word) => TITLE_WORDS[word] ?? word.charAt(0).toUpperCase() + word.slice(1))
        .join(' '),
    )
    .join(' / ');
}

function walk(dir, pages) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith('_') || name.startsWith('@')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      walk(full, pages);
      continue;
    }
    if (name !== 'page.tsx') continue;
    const rel = relative(appDir, dir);
    const segments = rel
      .split('/')
      .filter(
        (segment) =>
          segment && segment !== '.' && !segment.startsWith('(') && !segment.startsWith('_'),
      );
    if (segments.some((segment) => segment.includes('[') || segment.startsWith('@'))) continue;
    const path = segments.length ? `/${segments.join('/')}` : '/';
    pages.push(path);
  }
}

const paths = [];
walk(appDir, paths);
const unique = [...new Set(paths)].sort((a, b) => a.localeCompare(b));
const slugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const entries = unique.map((path) => {
  const slug = sitePageSlugFromPath(path);
  if (slug.length > 120 || !slugPattern.test(slug)) {
    throw new Error(`Site page slug is invalid for ${path}: ${slug}`);
  }
  return { path, title: titleFromPath(path), slug };
});

const slugs = new Set(entries.map((entry) => entry.slug));
if (slugs.size !== entries.length) {
  throw new Error('Site page slugs are not unique');
}

const body = entries
  .map(
    (entry) =>
      `  { path: ${JSON.stringify(entry.path)}, title: ${JSON.stringify(entry.title)}, slug: ${JSON.stringify(entry.slug)} },`,
  )
  .join('\n');

writeFileSync(
  outFile,
  `/** Generated by scripts/generate-site-pages.mjs. Do not edit by hand. */\nexport const SITE_PAGE_CATALOG = [\n${body}\n] as const;\n`,
);

console.log(`Wrote ${entries.length} site pages to ${outFile}`);
